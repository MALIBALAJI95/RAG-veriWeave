"""Pydantic schemas for chat queries, citations, retrieved chunks, and responses."""

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field
from backend.app.routing.schemas import RoutingDecision, RoutingMode
from backend.app.schemas.strategy import RetrievalStrategy


class MetadataFilter(BaseModel):
    """Filter criteria applied across vector and lexical retrieval."""
    doc_id: Optional[str] = Field(default=None, description="Filter by document UUID")
    filename: Optional[str] = Field(default=None, description="Filter by filename")
    page_number: Optional[int] = Field(default=None, description="Filter by page number")
    custom: Dict[str, Any] = Field(default_factory=dict, description="Arbitrary payload metadata filters")


class Citation(BaseModel):
    """Grounding source citation referencing document, database, or web origin."""
    citation_id: int = Field(description="Sequential citation number (1, 2, ...)")
    doc_id: str = Field(description="Parent document UUID or source category")
    filename: str = Field(description="Filename, SQL catalog identifier, or web source")
    page_number: int = Field(description="Page number (1-indexed)")
    chunk_index: int = Field(description="Index of the chunk in the document")
    score: float = Field(description="Relevance or similarity score (0.0 to 1.0)")
    snippet: str = Field(description="Representative excerpt from the source chunk")


class RetrievedChunk(BaseModel):
    """Raw chunk retrieved from vector/lexical store with provenance and scores."""
    chunk_id: str
    doc_id: str
    filename: str
    page_number: int
    chunk_index: int
    text: str
    score: float
    original_rank: Optional[int] = Field(default=None, description="Rank within the initial retrieval pass")
    rerank_score: Optional[float] = Field(default=None, description="Cross-encoder reranking score if applied")
    retrieval_method: Optional[str] = Field(default="dense", description="Method that retrieved this chunk")
    metadata: Dict[str, Any] = Field(default_factory=dict)


class RetrievalMetadata(BaseModel):
    """Internal diagnostic information describing the retrieval pipeline execution."""
    strategy: RetrievalStrategy
    generated_queries: List[str] = Field(default_factory=list, description="Sub-queries or variants generated by LLM")
    hypothetical_document: Optional[str] = Field(default=None, description="HyDE synthesized passage if applicable")
    sub_queries: List[str] = Field(default_factory=list, description="Decomposed sub-queries if applicable")
    fusion_applied: bool = False
    reranking_applied: bool = False
    raw_candidate_count: int = 0
    returned_candidate_count: int = 0
    retrieval_latency_ms: float = 0.0


from backend.app.routing.evidence import EvidenceItem


class ChatRequest(BaseModel):
    """User request to query the RAG system."""
    query: str = Field(min_length=1, max_length=2000, description="User's natural language question")
    routing_mode: Optional[RoutingMode] = Field(
        default=RoutingMode.AUTO,
        description="Routing mode: auto, document_only, sql_only, web_only, multi_source",
    )
    retrieval_strategy: Optional[RetrievalStrategy] = Field(
        default=RetrievalStrategy.BASELINE,
        description="Retrieval strategy: baseline, multi_query, hyde, decomposition, fusion, hybrid, hybrid_rerank, rerank",
    )
    top_k: int = Field(default=4, ge=1, le=20, description="Number of top chunks to retrieve")
    score_threshold: Optional[float] = Field(
        default=None,
        ge=0.0,
        le=1.0,
        description="Minimum similarity score filter (optional)",
    )
    rerank: Optional[bool] = Field(
        default=False,
        description="Whether to apply cross-encoder reranking to retrieved candidates",
    )
    filters: Optional[MetadataFilter] = Field(
        default=None,
        description="Optional metadata filtering (doc_id, filename, page_number)",
    )
    # Backward compatibility field from Phase 1
    doc_id_filter: Optional[str] = Field(
        default=None,
        description="Optional document ID filter (backward compatibility)",
    )
    adaptive: Optional[bool] = Field(
        default=False,
        description="Whether to execute adaptive self-correcting RAG workflow via LangGraph",
    )


class ChatResponse(BaseModel):
    """Complete grounded answer returned to the user."""
    query: str
    answer: str
    citations: List[Citation]
    retrieved_chunks: List[RetrievedChunk]
    model_used: str
    latency_ms: float
    grounded: bool = True
    fallback_used: bool = False
    routing_decision: Optional[RoutingDecision] = Field(
        default=None,
        description="Intelligent routing decision details (route, confidence, method, reasoning)",
    )
    retrieval_metadata: Optional[RetrievalMetadata] = Field(
        default=None,
        description="Diagnostic metadata detailing queries generated, fusion, and reranking",
    )
    evidence: List[EvidenceItem] = Field(
        default_factory=list,
        description="Unified cross-source evidence items (vector, SQL, web)",
    )
    adaptive_metadata: Optional[Any] = Field(
        default=None,
        description="Diagnostic metadata detailing LangGraph adaptive grading, rewrites, and validation",
    )
